/** Tags that don't name a theme (a typo, say): association.test.ts expects none. */
export const UNKNOWN_TAGS: string[] = [];

/** The curated themes with every word's tags folded in. */
export const THEMES: readonly Theme[] = (() => {
  const byName = new Map<string, Theme & { members: string[] }>();
  const out = CURATED.map((th) => ({ names: th.names, members: [...th.members] }));
  for (const th of out) for (const n of th.names) byName.set(n, th);
  for (const line of TAGS.split('\n')) {
    const [word, tags] = line.split(':');
    if (!word || !tags) continue;
    for (const tag of tags.trim().split(/\s+/)) {
      const th = byName.get(tag);
      if (!th) UNKNOWN_TAGS.push(`${word}: ${tag}`);
      else if (!th.members.includes(word)) th.members.push(word);
    }
  }
  return out;
})();

