// Packs a word list (one lowercase word per line) into src/words.packed.ts.
//
//   node packages/games/wordhoard/scripts/pack-words.mjs path/to/enable1.txt
//
// The list is ENABLE (Enhanced North American Benchmark Lexicon), public domain. Words are
// front-coded: each starts with a capital letter giving how many letters it shares with the word
// before it ('A' = 0), followed by the rest of the word. About a third of the plain list's size.
import { readFileSync, writeFileSync } from 'node:fs';

const [src] = process.argv.slice(2);
if (!src) throw new Error('Usage: node pack-words.mjs <word list>');
const words = [
  ...new Set(
    readFileSync(src, 'utf8')
      .split(/\r?\n/)
      .map((w) => w.trim().toLowerCase())
      .filter((w) => /^[a-z]{2,15}$/.test(w)),
  ),
].sort();
let prev = '';
let out = '';
for (const w of words) {
  let p = 0;
  while (p < 25 && p < w.length && w[p] === prev[p]) p++;
  out += String.fromCharCode(65 + p) + w.slice(p);
  prev = w;
}
const target = new URL('../src/words.packed.ts', import.meta.url);
writeFileSync(
  target,
  `// Generated by scripts/pack-words.mjs from ENABLE (public domain): ${words.length} words.\n// Do not edit.\nexport const PACKED_WORDS =\n  '${out}';\n`,
);
console.log(`${words.length} words, ${out.length} characters`);
