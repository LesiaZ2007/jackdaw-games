/**
 * What the computer players know about words: public, general knowledge (which words are animals,
 * what goes in a kitchen), never the key. A bot spymaster clues a theme that covers several of its
 * team's words; a bot operative reads a clue by the same table, as anyone at the table could.
 *
 * Every member is on the game's word list (src/words.ts) and no clue is (association.test.ts
 * checks), so a bot's clue is never one of the board's words. The first name of a theme is the
 * clue a bot gives; the others are other ways a person might say it, for reading human clues.
 */

export interface Theme {
  /** Clue words, the one bots give first. Upper case letters, one word each. */
  names: readonly string[];
  members: readonly string[];
}

const t = (names: string, members: string): Theme => ({
  names: names.split(' '),
  members: members.split(/\s+/).filter(Boolean),
});

